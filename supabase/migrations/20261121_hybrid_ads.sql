-- Régie publicitaire hybride Kora (Campagnes directes + VAST de secours + Mid-roll + Suivi vues/clics/revenus)

ALTER TABLE public.platform_settings
  ADD COLUMN IF NOT EXISTS ads_enabled boolean NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS midroll_enabled boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS midroll_interval_min int NOT NULL DEFAULT 20,
  ADD COLUMN IF NOT EXISTS vast_tag_url text NOT NULL DEFAULT '';

CREATE TABLE IF NOT EXISTS public.ad_campaigns (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  advertiser text NOT NULL,
  placement text NOT NULL DEFAULT 'preroll' CHECK (placement IN ('preroll', 'midroll')),
  media_type text NOT NULL DEFAULT 'video' CHECK (media_type IN ('video', 'image')),
  media_url text NOT NULL DEFAULT '',
  storage_path text,
  click_url text NOT NULL DEFAULT '',
  cta_label text NOT NULL DEFAULT 'En savoir plus',
  duration_sec int NOT NULL DEFAULT 15 CHECK (duration_sec BETWEEN 3 AND 120),
  skip_after_sec int NOT NULL DEFAULT 5 CHECK (skip_after_sec BETWEEN 0 AND 60),
  target_countries text[] NOT NULL DEFAULT '{}',
  cpm_xof int NOT NULL DEFAULT 1500 CHECK (cpm_xof >= 0),
  max_impressions int CHECK (max_impressions IS NULL OR max_impressions > 0),
  impressions_count int NOT NULL DEFAULT 0,
  clicks_count int NOT NULL DEFAULT 0,
  completions_count int NOT NULL DEFAULT 0,
  priority int NOT NULL DEFAULT 10 CHECK (priority BETWEEN 1 AND 100),
  active boolean NOT NULL DEFAULT true,
  starts_at timestamptz,
  ends_at timestamptz,
  created_by uuid REFERENCES public.accounts(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_ad_campaigns_active_placement
  ON public.ad_campaigns (active, placement, priority DESC);

ALTER TABLE public.ad_campaigns ENABLE ROW LEVEL SECURITY;

DO $$ BEGIN
  CREATE POLICY "admin gere campagnes pub"
    ON public.ad_campaigns
    FOR ALL
    TO authenticated
    USING (EXISTS (SELECT 1 FROM public.accounts a WHERE a.id = (SELECT auth.uid()) AND a.role = 'admin'))
    WITH CHECK (EXISTS (SELECT 1 FROM public.accounts a WHERE a.id = (SELECT auth.uid()) AND a.role = 'admin'));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

CREATE TABLE IF NOT EXISTS public.ad_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id bigint REFERENCES public.ad_campaigns(id) ON DELETE SET NULL,
  title_id bigint REFERENCES public.titles(id) ON DELETE SET NULL,
  event_type text NOT NULL CHECK (event_type IN ('impression', 'complete', 'click', 'skip', 'vast_impression')),
  placement text NOT NULL DEFAULT 'preroll' CHECK (placement IN ('preroll', 'midroll')),
  country text,
  user_id uuid REFERENCES public.accounts(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_ad_events_campaign_created
  ON public.ad_events (campaign_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_ad_events_created
  ON public.ad_events (created_at DESC);

ALTER TABLE public.ad_events ENABLE ROW LEVEL SECURITY;

DO $$ BEGIN
  CREATE POLICY "admin lit evenements pub"
    ON public.ad_events
    FOR SELECT
    TO authenticated
    USING (EXISTS (SELECT 1 FROM public.accounts a WHERE a.id = (SELECT auth.uid()) AND a.role = 'admin'));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- RPC sécurisée de sélection de campagne publicitaire active (appelée uniquement côté serveur via /api/ads)
CREATE OR REPLACE FUNCTION public.select_active_ad(
  p_placement text DEFAULT 'preroll',
  p_country text DEFAULT NULL
)
RETURNS TABLE (
  id bigint,
  name text,
  advertiser text,
  placement text,
  media_type text,
  media_url text,
  storage_path text,
  click_url text,
  cta_label text,
  duration_sec int,
  skip_after_sec int,
  priority int
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_country text := upper(trim(coalesce(p_country, '')));
  v_placement text := CASE WHEN p_placement = 'midroll' THEN 'midroll' ELSE 'preroll' END;
BEGIN
  RETURN QUERY
  SELECT
    c.id, c.name, c.advertiser, c.placement, c.media_type,
    c.media_url, c.storage_path, c.click_url, c.cta_label,
    c.duration_sec, c.skip_after_sec, c.priority
  FROM public.ad_campaigns c
  WHERE c.active = true
    AND c.placement = v_placement
    AND (c.starts_at IS NULL OR c.starts_at <= now())
    AND (c.ends_at IS NULL OR c.ends_at >= now())
    AND (c.max_impressions IS NULL OR c.impressions_count < c.max_impressions)
    AND (
      coalesce(array_length(c.target_countries, 1), 0) = 0
      OR (v_country <> '' AND v_country = ANY(c.target_countries))
    )
    AND (trim(coalesce(c.media_url, '')) <> '' OR trim(coalesce(c.storage_path, '')) <> '')
  ORDER BY (c.priority * (0.5 + random())) DESC
  LIMIT 1;
END;
$$;

-- RPC sécurisée d'enregistrement atomique d'événement publicitaire (vues, clics, complétions, skips)
CREATE OR REPLACE FUNCTION public.record_ad_event(
  p_campaign_id bigint DEFAULT NULL,
  p_title_id bigint DEFAULT NULL,
  p_event_type text DEFAULT 'impression',
  p_placement text DEFAULT 'preroll',
  p_country text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_event text := CASE
    WHEN p_event_type IN ('impression', 'complete', 'click', 'skip', 'vast_impression') THEN p_event_type
    ELSE 'impression'
  END;
  v_placement text := CASE WHEN p_placement = 'midroll' THEN 'midroll' ELSE 'preroll' END;
BEGIN
  INSERT INTO public.ad_events (campaign_id, title_id, event_type, placement, country, user_id)
  VALUES (p_campaign_id, p_title_id, v_event, v_placement, nullif(upper(trim(coalesce(p_country, ''))), ''), v_uid);

  IF p_campaign_id IS NOT NULL THEN
    IF v_event = 'impression' THEN
      UPDATE public.ad_campaigns SET impressions_count = impressions_count + 1, updated_at = now() WHERE id = p_campaign_id;
    ELSIF v_event = 'click' THEN
      UPDATE public.ad_campaigns SET clicks_count = clicks_count + 1, updated_at = now() WHERE id = p_campaign_id;
    ELSIF v_event = 'complete' THEN
      UPDATE public.ad_campaigns SET completions_count = completions_count + 1, updated_at = now() WHERE id = p_campaign_id;
    END IF;
  END IF;
END;
$$;

GRANT EXECUTE ON FUNCTION public.select_active_ad(text, text) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.record_ad_event(bigint, bigint, text, text, text) TO anon, authenticated;

-- Extension de l'accès lecture publique aux réglages publicitaires non-sensibles via get_ad_runtime_config
CREATE OR REPLACE FUNCTION public.get_ad_runtime_config()
RETURNS TABLE (
  ads_enabled boolean,
  midroll_enabled boolean,
  midroll_interval_min int,
  vast_tag_url text
)
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT
    coalesce(ads_enabled, true),
    coalesce(midroll_enabled, false),
    greatest(5, least(60, coalesce(midroll_interval_min, 20))),
    coalesce(vast_tag_url, '')
  FROM public.platform_settings
  WHERE id = 1
  LIMIT 1;
$$;

GRANT EXECUTE ON FUNCTION public.get_ad_runtime_config() TO anon, authenticated;

