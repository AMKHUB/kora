-- Enregistrement d'une intention de paiement SasPay en statut 'pending' (ne livre jamais l'abonnement)
CREATE OR REPLACE FUNCTION public.saspay_register_pending_payment(
  p_payment_id text,
  p_idempotency_key text,
  p_plan_id text,
  p_billing_cycle text,
  p_amount_xof integer,
  p_amount_decimal text,
  p_currency text,
  p_country_iso text,
  p_network_code text,
  p_provider_label text,
  p_checkout_url text DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_id bigint;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'Connexion requise';
  END IF;
  IF p_payment_id IS NULL OR length(trim(p_payment_id)) = 0 THEN
    RAISE EXCEPTION 'Identifiant de paiement SasPay manquant';
  END IF;
  IF p_plan_id NOT IN ('premium', 'family') THEN
    RAISE EXCEPTION 'Formule invalide';
  END IF;
  IF p_billing_cycle NOT IN ('month', 'year') THEN
    RAISE EXCEPTION 'Périodicité invalide';
  END IF;

  INSERT INTO public.payments (
    account_id,
    amount_xof,
    amount_decimal,
    currency,
    country_iso,
    network_code,
    plan_id,
    billing_cycle,
    provider,
    provider_ref,
    idempotency_key,
    checkout_url,
    status,
    created_at,
    updated_at
  )
  VALUES (
    v_uid,
    p_amount_xof,
    p_amount_decimal,
    coalesce(nullif(trim(p_currency), ''), 'XOF'),
    upper(trim(coalesce(p_country_iso, 'ML'))),
    trim(coalesce(p_network_code, '')),
    p_plan_id,
    p_billing_cycle,
    coalesce(nullif(trim(p_provider_label), ''), 'SasPay'),
    trim(p_payment_id),
    nullif(trim(coalesce(p_idempotency_key, '')), ''),
    nullif(trim(coalesce(p_checkout_url, '')), ''),
    'pending',
    now(),
    now()
  )
  ON CONFLICT (provider_ref) WHERE provider_ref IS NOT NULL
  DO UPDATE SET
    checkout_url = coalesce(EXCLUDED.checkout_url, public.payments.checkout_url),
    updated_at = now()
  RETURNING id INTO v_id;

  RETURN v_id;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.saspay_register_pending_payment(text, text, text, text, integer, text, text, text, text, text, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.saspay_register_pending_payment(text, text, text, text, integer, text, text, text, text, text, text) TO authenticated;

-- Validation et livraison idempotente d'un paiement SasPay vérifié (uniquement sur statut SUCCESS)
CREATE OR REPLACE FUNCTION public.saspay_apply_verified_transaction(
  p_gate_secret text,
  p_payment_id text,
  p_saspay_status text,
  p_charged_amount text DEFAULT NULL,
  p_net_amount text DEFAULT NULL,
  p_fee_amount text DEFAULT NULL,
  p_fee_charge_mode text DEFAULT NULL,
  p_currency text DEFAULT NULL,
  p_external_reference text DEFAULT NULL,
  p_event_key text DEFAULT NULL,
  p_raw_payload jsonb DEFAULT NULL,
  p_session_id text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_expected_secret text;
  v_pay record;
  v_days integer;
  v_period_end timestamptz;
  v_sub_id bigint;
  v_already_delivered boolean := false;
BEGIN
  SELECT gate_secret INTO v_expected_secret
  FROM public.private_server_gates
  WHERE gate_name = 'saspay_bff';

  IF v_expected_secret IS NULL OR p_gate_secret IS DISTINCT FROM v_expected_secret THEN
    RAISE EXCEPTION 'Appel serveur non autorisé';
  END IF;

  IF p_event_key IS NOT NULL AND length(trim(p_event_key)) > 0 THEN
    INSERT INTO public.saspay_webhook_logs (event_key, event_type, resource_id, payload)
    VALUES (trim(p_event_key), coalesce(p_raw_payload->>'event', 'verify'), p_payment_id, coalesce(p_raw_payload, '{}'::jsonb))
    ON CONFLICT (event_key) DO NOTHING;
  END IF;

  SELECT * INTO v_pay
  FROM public.payments
  WHERE provider_ref = trim(p_payment_id)
     OR (p_session_id IS NOT NULL AND length(trim(p_session_id)) > 0 AND provider_ref = trim(p_session_id))
  ORDER BY id DESC
  LIMIT 1
  FOR UPDATE;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('found', false, 'status', p_saspay_status, 'delivered', false);
  END IF;

  IF v_pay.provider_ref IS DISTINCT FROM trim(p_payment_id) AND length(trim(p_payment_id)) > 0 THEN
    UPDATE public.payments
    SET provider_ref = trim(p_payment_id)
    WHERE id = v_pay.id
      AND NOT EXISTS (SELECT 1 FROM public.payments p2 WHERE p2.provider_ref = trim(p_payment_id) AND p2.id <> v_pay.id);
    v_pay.provider_ref := trim(p_payment_id);
  END IF;

  v_already_delivered := (v_pay.fulfilled_at IS NOT NULL OR v_pay.status = 'paid');

  IF upper(trim(p_saspay_status)) = 'SUCCESS' THEN
    IF NOT v_already_delivered THEN
      v_days := CASE WHEN v_pay.billing_cycle = 'year' THEN 365 ELSE 30 END;
      v_period_end := now() + make_interval(days => v_days);

      UPDATE public.subscriptions
      SET status = 'expired'
      WHERE account_id = v_pay.account_id AND status = 'active';

      INSERT INTO public.subscriptions (
        account_id,
        plan_id,
        status,
        current_period_end,
        cancel_at_period_end,
        provider,
        provider_ref,
        created_at
      )
      VALUES (
        v_pay.account_id,
        coalesce(v_pay.plan_id, 'premium'),
        'active',
        v_period_end,
        false,
        v_pay.provider,
        v_pay.provider_ref,
        now()
      )
      RETURNING id INTO v_sub_id;

      UPDATE public.payments
      SET status = 'paid',
          subscription_id = v_sub_id,
          charged_amount = coalesce(p_charged_amount, charged_amount, amount_decimal),
          net_amount = coalesce(p_net_amount, net_amount, amount_decimal),
          fee_amount = coalesce(p_fee_amount, fee_amount),
          fee_charge_mode = coalesce(p_fee_charge_mode, fee_charge_mode),
          currency = coalesce(nullif(trim(p_currency), ''), currency),
          external_reference = coalesce(nullif(trim(p_external_reference), ''), external_reference),
          fulfilled_at = now(),
          updated_at = now()
      WHERE id = v_pay.id;

      INSERT INTO public.notifications (account_id, title, body, kind, link)
      VALUES (
        v_pay.account_id,
        'Abonnement Kora activé',
        'Votre paiement SasPay (' || coalesce(p_charged_amount, v_pay.amount_decimal, v_pay.amount_xof::text) || ' ' || coalesce(v_pay.currency, 'XOF') || ') a été confirmé.',
        'account',
        '#/abonnement'
      );
    ELSE
      UPDATE public.payments
      SET charged_amount = coalesce(p_charged_amount, charged_amount),
          net_amount = coalesce(p_net_amount, net_amount),
          fee_amount = coalesce(p_fee_amount, fee_amount),
          fee_charge_mode = coalesce(p_fee_charge_mode, fee_charge_mode),
          external_reference = coalesce(nullif(trim(p_external_reference), ''), external_reference),
          updated_at = now()
      WHERE id = v_pay.id;
    END IF;

    RETURN jsonb_build_object(
      'found', true,
      'status', 'SUCCESS',
      'delivered', true,
      'already_delivered', v_already_delivered,
      'plan_id', coalesce(v_pay.plan_id, 'premium'),
      'billing_cycle', coalesce(v_pay.billing_cycle, 'month'),
      'account_id', v_pay.account_id
    );
  ELSIF upper(trim(p_saspay_status)) IN ('FAILED', 'CANCELLED', 'EXPIRED') THEN
    IF NOT v_already_delivered THEN
      UPDATE public.payments
      SET status = lower(trim(p_saspay_status)),
          updated_at = now()
      WHERE id = v_pay.id;
    END IF;
    RETURN jsonb_build_object(
      'found', true,
      'status', upper(trim(p_saspay_status)),
      'delivered', v_already_delivered,
      'plan_id', v_pay.plan_id
    );
  END IF;

  RETURN jsonb_build_object(
    'found', true,
    'status', upper(trim(coalesce(p_saspay_status, 'PENDING'))),
    'delivered', v_already_delivered,
    'plan_id', v_pay.plan_id
  );
END;
$$;

-- Enregistrement et suivi des retraits (payouts) SasPay
CREATE OR REPLACE FUNCTION public.saspay_upsert_payout(
  p_gate_secret text,
  p_account_id uuid,
  p_saspay_payout_id text,
  p_idempotency_key text,
  p_amount text,
  p_currency text,
  p_country text,
  p_method text,
  p_recipient_msisdn text,
  p_description text DEFAULT NULL,
  p_status text DEFAULT 'PENDING',
  p_debited_amount text DEFAULT NULL,
  p_net_amount text DEFAULT NULL,
  p_fee_charge_mode text DEFAULT NULL,
  p_reference text DEFAULT NULL,
  p_external_reference text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_expected_secret text;
  v_row public.saspay_payouts;
BEGIN
  SELECT gate_secret INTO v_expected_secret
  FROM public.private_server_gates
  WHERE gate_name = 'saspay_bff';

  IF v_expected_secret IS NULL OR p_gate_secret IS DISTINCT FROM v_expected_secret THEN
    RAISE EXCEPTION 'Appel serveur non autorisé';
  END IF;

  INSERT INTO public.saspay_payouts (
    account_id,
    saspay_payout_id,
    idempotency_key,
    amount,
    debited_amount,
    net_amount,
    fee_charge_mode,
    currency,
    country,
    method,
    recipient_msisdn,
    description,
    status,
    reference,
    external_reference,
    created_at,
    updated_at
  )
  VALUES (
    p_account_id,
    p_saspay_payout_id,
    p_idempotency_key,
    p_amount,
    p_debited_amount,
    p_net_amount,
    p_fee_charge_mode,
    p_currency,
    p_country,
    p_method,
    p_recipient_msisdn,
    p_description,
    upper(trim(coalesce(p_status, 'PENDING'))),
    p_reference,
    p_external_reference,
    now(),
    now()
  )
  ON CONFLICT (idempotency_key)
  DO UPDATE SET
    saspay_payout_id = coalesce(EXCLUDED.saspay_payout_id, public.saspay_payouts.saspay_payout_id),
    status = coalesce(EXCLUDED.status, public.saspay_payouts.status),
    debited_amount = coalesce(EXCLUDED.debited_amount, public.saspay_payouts.debited_amount),
    net_amount = coalesce(EXCLUDED.net_amount, public.saspay_payouts.net_amount),
    fee_charge_mode = coalesce(EXCLUDED.fee_charge_mode, public.saspay_payouts.fee_charge_mode),
    reference = coalesce(EXCLUDED.reference, public.saspay_payouts.reference),
    external_reference = coalesce(EXCLUDED.external_reference, public.saspay_payouts.external_reference),
    updated_at = now()
  RETURNING * INTO v_row;

  RETURN to_jsonb(v_row);
END;
$$;
